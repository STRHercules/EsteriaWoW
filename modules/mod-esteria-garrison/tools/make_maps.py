"""Clone the client's winning Map.dbc (the housing patch) and append the six Draenor garrison tier maps.

The new patch sorts after Patch-ZZZZZZZZZZZZZZZZZZZZZZZZZHousingDev.MPQ, so it replaces that Map.dbc and must
keep every row it already had. Directory is the map id: the client loads World\\Maps\\<id>\\<id>.wdt.
AreaTableID stays the template's, so the client does not look up an area this Map.dbc does not name.
"""
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODULE = HERE.parent
sys.path.insert(0, str(MODULE.parents[1] / "tools"))
from cars_mount_pack import Storm  # noqa: E402

CLIENT = Path(r"G:\risServer\Esteria - Client")
STORMLIB = CLIENT / "StormLib.dll"
PATCH_NAME = "Patch-ZZZZZZZZZZZZZZZZZZZZZZZZZZGarrison.MPQ"
MAP_DBC = r"DBFilesClient\Map.dbc"
TEMPLATE = 35
# id: directory, name. InstanceType 1, 40 players, cloned from map 35.
MAPS = {
    1158: ("1158", "Lunarfall"),
    1331: ("1331", "Lunarfall"),
    1159: ("1159", "Lunarfall"),
    1152: ("1152", "Frostwall"),
    1330: ("1330", "Frostwall"),
    1153: ("1153", "Frostwall"),
}
MAP_TEXT = {1} | set(range(5, 21)) | set(range(23, 39)) | set(range(40, 56))
MAP_FLOATS = {58, 60, 61}


def read_wdbc(data):
    assert data[:4] == b"WDBC", "not a WDBC file"
    count, fields, size, strings = struct.unpack_from("<4I", data, 4)
    rows = [data[20 + i * size:20 + (i + 1) * size] for i in range(count)]
    blob = data[20 + count * size:20 + count * size + strings]
    return fields, size, rows, blob


def q(text):
    return "'" + str(text).replace("\\", "\\\\").replace("'", "''") + "'"


def winning(storm):
    data_dir = CLIENT / "Data"
    found = [(f"data\\{p.name.lower()}", p) for p in data_dir.glob("patch-*") if p.suffix.lower() == ".mpq"]
    found += [(f"data\\enus\\{p.name.lower()}", p) for p in (data_dir / "enUS").glob("patch-enus-*")
              if p.suffix.lower() == ".mpq"]
    for _, archive in sorted(found, reverse=True):
        if archive.name.lower() == PATCH_NAME.lower():
            continue
        handle = storm.open_archive(archive)
        try:
            return archive, storm.read(handle, MAP_DBC)
        except OSError:
            continue
        finally:
            storm.dll.SFileCloseArchive(handle)
    raise SystemExit("no patch MPQ holds Map.dbc")


def sql_values(strings, row, texts):
    values = []
    for i, v in enumerate(row):
        if i in texts:
            values.append(q(texts[i]))
        elif i in MAP_TEXT:
            values.append(q(strings[v:strings.index(b"\0", v)].decode("utf-8")))
        elif i in MAP_FLOATS:
            values.append(repr(struct.unpack("<f", struct.pack("<I", v))[0]))
        else:
            values.append(str(struct.unpack("<i", struct.pack("<I", v))[0]))
    return values


def main():
    storm = Storm(STORMLIB)
    source, original = winning(storm)
    fields, size, rows, strings = read_wdbc(original)
    assert (fields, size) == (66, 264), f"Map.dbc layout {fields}x{size}"
    base = next(list(struct.unpack("<66I", r)) for r in rows if struct.unpack_from("<I", r)[0] == TEMPLATE)
    taken = {struct.unpack_from("<I", r)[0] for r in rows}
    strings = bytearray(strings)
    built = []
    for map_id, (directory, name) in MAPS.items():
        assert map_id not in taken, f"map {map_id} is already in {source.name}"
        row = list(base)
        row[0], row[2], row[65] = map_id, 1, 40
        texts = {1: directory, 5: name}
        for field, text in texts.items():
            row[field] = len(strings)
            strings += text.encode("utf-8") + b"\0"
        rows.append(struct.pack("<66I", *row))
        built.append((row, texts))
    out = b"WDBC" + struct.pack("<4I", len(rows), fields, size, len(strings)) + b"".join(rows) + bytes(strings)
    target = CLIENT / "Data" / PATCH_NAME
    if target.exists():
        target.unlink()
    storm.create_archive(target, {MAP_DBC: out})
    handle = storm.open_archive(target)
    try:
        assert storm.read(handle, MAP_DBC) == out
    finally:
        storm.dll.SFileCloseArchive(handle)

    original_strings = read_wdbc(original)[3]
    ids = ", ".join(str(i) for i in MAPS)
    lines = [
        "-- Generated by modules/mod-esteria-garrison/tools/make_maps.py from the client's winning Map.dbc.",
        "-- Six Draenor garrison tier maps. AreaTableID is the template map's, so no new areatable_dbc row is required.",
        f"-- Source: {source.name}",
        "",
        f"DELETE FROM `map_dbc` WHERE `ID` IN ({ids});",
        f"DELETE FROM `instance_template` WHERE `map` IN ({ids});",
        f"DELETE FROM `mapdifficulty_dbc` WHERE `MapID` IN ({ids});",
    ]
    for row, texts in built:
        lines.append("INSERT INTO `map_dbc` VALUES (" + ", ".join(sql_values(original_strings, row, texts)) + ");")
    for map_id in MAPS:
        lines.append(f"INSERT INTO `instance_template` (`map`, `parent`, `script`, `allowMount`) VALUES ({map_id}, 0, '', 1);")
        lines.append("INSERT INTO `mapdifficulty_dbc` (`ID`, `MapID`, `Difficulty`, `Message_Lang_Mask`, `RaidDuration`, `MaxPlayers`) "
                     f"VALUES ({map_id}, {map_id}, 0, 16712188, 0, 40);")
    sql = MODULE / "sql" / "world" / "garrison_world.sql"
    sql.parent.mkdir(parents=True, exist_ok=True)
    sql.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {target} on top of {source.name}")
    print(f"wrote {sql}")


if __name__ == "__main__":
    main()
