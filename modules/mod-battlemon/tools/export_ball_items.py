#!/usr/bin/env python3
"""Write item_template rows for sealed-Pokemon Poke Balls: one per species and shiny state.

    python tools/export_ball_items.py

Entries follow src/BattlemonBall.h: 960000 + species id, shiny 962000 + species id. Output:
data/sql/db-world/base/2026_11_05_05_battlemon_ball_items.sql
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SQL_DIR = os.path.join(ROOT, 'data', 'sql', 'db-world', 'base')
ITEM_BASE, SHINY_OFFSET = 960000, 2000   # keep in step with src/BattlemonBall.h
# Placeholders needing a client-side choice, set once here:
#   DISPLAY_ID - existing ItemDisplayInfo row used as the icon (6418 is the Hearthstone's round stone).
#   USE_SPELL  - the client only offers right-click on an item that has a "Use:" spell, and shows that spell's
#                text. The server claims the click (item_battlemon_ball) so the spell never casts, but the
#                tooltip still reads like the spell until a custom client spell is patched in.
DISPLAY_ID, USE_SPELL = 6418, 8690
ITEM_FLAG_NO_USER_DESTROY = 0x20


def species():
    out = {}
    for path in sorted(glob.glob(os.path.join(SQL_DIR, '*catalog_species.sql'))):
        text = open(path, encoding='utf-8').read()
        for sid, _, name in re.findall(r"^\((\d+), '(\w+)', '((?:[^']|'')*)'", text, re.M):
            out[int(sid)] = name.replace("''", "'")
    return out


def q(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    names = species()
    rows = []
    for sid, name in sorted(names.items()):
        for shiny in (False, True):
            entry = ITEM_BASE + (SHINY_OFFSET if shiny else 0) + sid
            title = ('Shiny ' if shiny else '') + 'Poké Ball: ' + name
            desc = 'Contains ' + ('a shiny ' if shiny else '') + name + '. Use it to release the Pokémon into your collection.'
            rows.append(f"({entry}, 15, 0, {q(title)}, {DISPLAY_ID}, {3 if shiny else 1}, {ITEM_FLAG_NO_USER_DESTROY}, "
                        f"1, 0, 0, 0, 1, {USE_SPELL}, 0, 0, -1, {q(desc)}, 'item_battlemon_ball', 12340)")
    lines = [
        '-- Poke Ball items for sealed Pokemon: one template per species and shiny state.',
        '-- Generated by tools/export_ball_items.py; re-run it instead of editing by hand.',
        '-- SellPrice 0 means vendors refuse them, and NO_USER_DESTROY stops players deleting a Pokemon by accident.',
        '',
        f'DELETE FROM `item_template` WHERE `entry` BETWEEN {ITEM_BASE} AND {ITEM_BASE + 2 * SHINY_OFFSET - 1};',
        'INSERT INTO `item_template` (`entry`, `class`, `subclass`, `name`, `displayid`, `Quality`, `Flags`, `BuyCount`, '
        '`BuyPrice`, `SellPrice`, `InventoryType`, `stackable`, `spellid_1`, `spelltrigger_1`, `spellcharges_1`, '
        '`spellcooldown_1`, `description`, `ScriptName`, `VerifiedBuild`) VALUES',
        ',\n'.join(rows) + ';',
    ]
    out = os.path.join(SQL_DIR, '2026_11_05_05_battlemon_ball_items.sql')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{len(rows)} items for {len(names)} species -> {out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
