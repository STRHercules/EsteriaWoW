"""Section 5 of the housing spec (household services): the world rows and client DBC rows make_slice.py adds.

    sql/world/housing_household_world.sql  catalog rows 40217-40264 (category 9, Services), their gameobject templates,
                                           the hidden helpers (banker, mailbox, spell focuses), the House Hearthstone
                                           item and its spell (spell_dbc, cloned from the client's Hearthstone)
    client patch                           Spell.dbc and Item.dbc rows for the House Hearthstone, and its cast visual

Called by make_slice.main(); every row is regenerated, so the file can be reapplied (after housing_world.sql, which
rebuilds the catalog).
"""
from pathlib import Path

import make_adventure as adv

MODULE = Path(__file__).resolve().parents[1]
OUT = MODULE / "sql/world/housing_household_world.sql"

SERVICES = 9                      # the catalog category the Editor calls Services
GO_BASE = 9506120                 # + decor - 40217
FOCUS_GO_BASE, HIDDEN_MAILBOX, HIDDEN_BANKER = 9506100, 9506110, 9505020
FIGURE_DECOR = 5564  # NPCs show a statue in the catalog and the placement preview (a bare character model drew white)
HEARTH_ITEM, HEARTH_SPELL, HEARTH_FROM_ITEM, HEARTH_FROM_SPELL = 9500200, 9500102, 6948, 8690
# The spell focuses a station can be (SpellFocusObject.dbc), as HousingHousehold.inc FocusIds orders them
FOCUSES = [(1, "Anvil"), (3, "Forge"), (4, "Cooking Fire"), (663, "Alchemy Lab"), (623, "Black Anvil"), (543, "Black Forge"),
           (1552, "Runeforge")]
# decor id: (name, the retail decor whose model it borrows (None: a figure), gameobject type)
PIECES = {
    40217: ("Innkeeper", None, 2), 40218: ("Banker", None, 2), 40219: ("Bank Vault", 1322, 2), 40220: ("Bank Chest", 4482, 2),
    40221: ("Guild Vault", 15460, 34), 40222: ("Thunder Totem Mailbox", 15741, 2), 40223: ("Explorer's Mailbox", 26374, 2),
    40224: ("Repair Smith", None, 2), 40225: ("Repair Bench", 2226, 2), 40226: ("Auctioneer", None, 2),
    40227: ("Small Storage Chest", 1280, 2), 40228: ("Storage Chest", 9243, 2), 40229: ("Large Storage Chest", 2437, 2),
    40230: ("Anvil", 11371, 2), 40231: ("Runic Anvil", 11375, 2), 40232: ("Forge", 11274, 2), 40233: ("Crystal Forge", 11374, 2),
    40234: ("Cooking Fire", 4450, 2), 40235: ("Cooking Grill", 8236, 2), 40236: ("Alchemy Lab", 11378, 2),
    40237: ("Black Anvil", 14590, 2), 40238: ("Black Forge", 14631, 2), 40239: ("Runeforge", 5888, 2),
}
PROFESSIONS = ["Alchemy", "Blacksmithing", "Cooking", "Enchanting", "Engineering", "First Aid", "Fishing", "Herbalism",
               "Inscription", "Jewelcrafting", "Leatherworking", "Mining", "Skinning", "Tailoring"]
for i, name in enumerate(PROFESSIONS):
    PIECES[40251 + i] = (name + " Trainer", None, 2)

# The House Hearthstone's cast visual: SpellVisual.dbc row (HEARTH_VISUAL), or the 3.3.5 Hearthstone's when None
HEARTH_VISUAL = None


def world_sql(display_of):
    q = adv.q
    lines = ["-- Generated by modules/mod-esteria-housing/tools/make_household.py (make_slice.py). Do not edit.",
             "-- Housing section 5: household services, storage chests, crafting stations and the House Hearthstone.", "",
             "DELETE FROM `housing_decor_catalog` WHERE `decor_id` BETWEEN 40217 AND 40264;",
             f"DELETE FROM `gameobject_template` WHERE `entry` BETWEEN {FOCUS_GO_BASE} AND {GO_BASE + 99};",
             "-- Hidden helpers the core's handlers need beside an object: a spell focus (display 0, 10 yd), a mailbox."]
    for i, (focus, name) in enumerate(FOCUSES):
        lines.append(f"INSERT INTO `gameobject_template` (`entry`, `type`, `displayId`, `name`, `size`, `Data0`, `Data1`) VALUES "
                     f"({FOCUS_GO_BASE + i}, 8, 0, {q(name)}, 1, {focus}, 10);")
    # a real model (the 3.3.5 mailbox), spawned at 1%: the client measures its mail window's range against the object's
    # model every frame (CGGameObject_C_TypeBase::CheckRange) and crashes on a mailbox with none
    lines.append(f"INSERT INTO `gameobject_template` (`entry`, `type`, `displayId`, `name`, `size`) VALUES "
                 f"({HIDDEN_MAILBOX}, 19, 1907, 'Mailbox', 1);")
    lines.append("-- The pieces: type 2 (questgiver, no quests) opens the script's gossip; the guild vault is the core's own (34). "
                 "A figure's object is never spawned.")
    for decor, (name, borrow, gotype) in sorted(PIECES.items()):
        display, fdid = display_of[borrow if borrow else FIGURE_DECOR]
        script = "'go_esteria_housing_collection'" if gotype == 2 else "''"
        lines.append(f"INSERT INTO `gameobject_template` (`entry`, `type`, `displayId`, `name`, `size`, `ScriptName`) VALUES "
                     f"({GO_BASE + decor - 40217}, {gotype}, {display}, {q(name)}, 1, {script});")
        lines.append(f"INSERT INTO `housing_decor_catalog` (`decor_id`, `model_fdid`, `display_id`, `gameobject_entry`, `name`, "
                     f"`category`, `surface`, `budget_cost`, `min_scale`, `max_scale`, `origin`, `enabled`) VALUES ({decor}, {fdid}, "
                     f"{display}, {GO_BASE + decor - 40217}, {q(name)}, {SERVICES}, 0, 1, 0.5, 2, 'retail', 1);")
    lines += ["", "-- A bank vault's hidden banker (11686: the invisible trigger model), never selectable.",
              f"DELETE FROM `creature_template_model` WHERE `CreatureID` = {HIDDEN_BANKER};",
              f"DELETE FROM `creature_template` WHERE `entry` = {HIDDEN_BANKER};",
              f"INSERT INTO `creature_template` (`entry`, `name`, `minlevel`, `maxlevel`, `faction`, `npcflag`, `unit_class`, `unit_flags`, "
              f"`type`, `flags_extra`) VALUES ({HIDDEN_BANKER}, 'Vault', 80, 80, 35, 131072, 1, {0x02000000 | 0x2}, 10, 64);",
              f"INSERT INTO `creature_template_model` (`CreatureID`, `Idx`, `CreatureDisplayID`, `DisplayScale`, `Probability`) VALUES "
              f"({HIDDEN_BANKER}, 0, 11686, 1, 1);",
              "", "-- The House Hearthstone: the Hearthstone's row, with its own spell (cooldown: EsteriaHousing.HearthCooldownMinutes).",
              f"DELETE FROM `item_template` WHERE `entry` = {HEARTH_ITEM};",
              "DROP TEMPORARY TABLE IF EXISTS `housing_hearth_item`;",
              f"CREATE TEMPORARY TABLE `housing_hearth_item` AS SELECT * FROM `item_template` WHERE `entry` = {HEARTH_FROM_ITEM};",
              f"UPDATE `housing_hearth_item` SET `entry` = {HEARTH_ITEM}, `name` = 'House Hearthstone', `spellid_1` = {HEARTH_SPELL}, "
              "`spellcooldown_1` = 1800000, `spellcategory_1` = 0, `spellcategorycooldown_1` = -1, "
              "`description` = 'Returns you to the house whose innkeeper you bound it to.';",
              "INSERT INTO `item_template` SELECT * FROM `housing_hearth_item`;",
              "DROP TEMPORARY TABLE `housing_hearth_item`;"]
    return lines


def patch_files(winning_dbc, append_rows, storm, client, display_of, built):
    """The client's House Hearthstone rows (Spell.dbc, Item.dbc), and the world SQL with the spell's server copy. built: the
    patch's files so far; its Spell.dbc (section 3's rows) is the one these rows go on."""
    files = {}
    name = r"DBFilesClient\Spell.dbc"
    spell_dbc = built.get(name) or winning_dbc(storm, client, name)[1]
    spells, text_of = adv.dbc_rows(spell_dbc)
    base = spells[HEARTH_FROM_SPELL]
    w, texts = adv.spell_row(base, HEARTH_SPELL, "House Hearthstone", "Returns you to the house whose innkeeper you bound it to.",
                             "Returns you to your bound house.", base[133], 30 * 60 * 1000)
    if HEARTH_VISUAL:
        w[131] = HEARTH_VISUAL
    files[name] = append_rows(spell_dbc, 234, 936, [(w, dict(texts))])
    _, item_dbc = winning_dbc(storm, client, r"DBFilesClient\Item.dbc")
    items, _ = adv.dbc_rows(item_dbc)
    row = list(items[HEARTH_FROM_ITEM])
    row[0] = HEARTH_ITEM
    files[r"DBFilesClient\Item.dbc"] = append_rows(item_dbc, 8, 32, [(row, {})])
    lines = world_sql(display_of)
    lines += ["", f"DELETE FROM `spell_dbc` WHERE `ID` = {HEARTH_SPELL};",
              f"DELETE FROM `spell_script_names` WHERE `spell_id` = {HEARTH_SPELL};",
              adv.spell_sql(w, texts, text_of),
              f"INSERT INTO `spell_script_names` (`spell_id`, `ScriptName`) VALUES ({HEARTH_SPELL}, 'spell_esteria_housing_hearth');"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote", OUT)
    return files
