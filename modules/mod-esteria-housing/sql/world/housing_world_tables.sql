-- Retail room kinds (HouseRoom) and the pieces each is built from (RoomComponent + RoomComponentOption, Generic
-- theme), generated by wowdecomp docs/housing/tools/phase3/make_kit.py. Pieces are type-14 GameObjects showing
-- retail\<fdid>.wmo; a wall with go_door is a socket another room can join through.
DROP TABLE IF EXISTS `housing_room_piece`; -- Phase 2a's fixed single room
CREATE TABLE IF NOT EXISTS `housing_room_kind` (
  `kind`  INT UNSIGNED NOT NULL COMMENT 'HouseRoom.ID (retail)',
  `name`  VARCHAR(100) NOT NULL DEFAULT '',
  `min_x` FLOAT NOT NULL, `min_y` FLOAT NOT NULL, `min_z` FLOAT NOT NULL,
  `max_x` FLOAT NOT NULL, `max_y` FLOAT NOT NULL, `max_z` FLOAT NOT NULL COMMENT 'RoomWmoData.BoundingBox',
  PRIMARY KEY (`kind`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

DROP TABLE IF EXISTS `housing_room_kit`; -- generated data; dropped so new columns arrive
CREATE TABLE IF NOT EXISTS `housing_room_kit` (
  `kind`     INT UNSIGNED NOT NULL,
  `piece_id` INT UNSIGNED NOT NULL COMMENT 'RoomComponent.ID (retail)',
  `type`     TINYINT UNSIGNED NOT NULL COMMENT '1 wall 2 floor 3 ceiling',
  `pos_x` FLOAT NOT NULL, `pos_y` FLOAT NOT NULL, `pos_z` FLOAT NOT NULL,
  `rot_deg`  FLOAT NOT NULL COMMENT 'RoomComponent.OffsetRot z, applied clockwise',
  `go_solid` INT UNSIGNED NOT NULL,
  `go_door`  INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'wall with a 3 yd door; non-zero makes the piece a socket',
  `go_wide`  INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'wall with an 11 yd opening, for hallway-width neighbours',
  `width`    FLOAT NOT NULL DEFAULT 0 COMMENT 'wall length, sockets only',
  `go_door_frame` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'frame centred on a door joint (covers the floor strip)',
  `go_wide_frame` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'frame centred on a wide joint',
  PRIMARY KEY (`kind`, `piece_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

