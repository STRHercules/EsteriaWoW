#!/usr/bin/env python3
"""The CoA world-database rows the imported spells need, and only those.

  python coa_sql_slice.py --coa-core R:/.../azerothcore-wotlk-coa

Replays CoA's world updates (data/sql/updates/db_world then pending_db_world,
in file order) for a handful of spell tables into a scratch schema built from
Esteria's own table definitions, so a row Esteria's schema cannot hold fails
there and is counted rather than shipped. Then it keeps the rows for spells in
client-patch/coa_manifest.json, and spell_script_names rows only for scripts
that exist in src/coa, and writes data/sql/db-world/cw_coa_scripts.sql.

Needs the ac-database container (docker exec); the scratch schema is dropped.
"""
import argparse
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MODULE = os.path.dirname(HERE)
SCRATCH = "coa_slice"
# table -> (spell id column, what it means), all keyed on |spell id|
TABLES = {
    "spell_script_names": "spell_id",
    "spell_proc": "SpellId",
    "spell_bonus_data": "entry",
    "spell_custom_attr": "spell_id",
    "spell_linked_spell": "spell_trigger",
    "spell_target_position": "ID",
}
STATEMENT = re.compile(r"^\s*(?:DELETE\s+FROM|INSERT\s+INTO|REPLACE\s+INTO|UPDATE)\s+`?(\w+)`?", re.I)


def mysql(sql, database=""):
    cmd = ["docker", "exec", "-i", "ac-database", "sh", "-c",
           'mysql -uroot -p"$MYSQL_ROOT_PASSWORD" --force -N %s' % database]
    return subprocess.run(cmd, input=sql.encode("utf-8"), capture_output=True)


def statements(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    text = "\n".join(line for line in text.split("\n") if not line.lstrip().startswith("--"))
    for stmt in re.split(r";\s*\n", text):
        m = STATEMENT.match(stmt)
        if m and m.group(1).lower() in TABLES:
            yield stmt.strip() + ";"
        elif re.match(r"^\s*SET\s+@", stmt, re.I):
            yield stmt.strip() + ";"     # a variable a following row uses


def ported_scripts():
    names = set()
    coa = os.path.join(MODULE, "src", "coa")
    for name in os.listdir(coa):
        if name.endswith(".cpp"):
            text = open(os.path.join(coa, name), encoding="utf-8", errors="replace").read()
            names.update(re.findall(r"RegisterSpell\w*\(\s*(\w+)", text))
            # RegisterSpellScriptWithArgs(class, "script_name", ...) names its script in the second argument
            names.update(re.findall(r"RegisterSpellScriptWithArgs\(\s*\w+\s*,\s*\"(\w+)\"", text))
            names.update(re.findall(r"(?:SpellScriptLoader|AuraScript|SpellScript)\(\"(\w+)\"\)", text))
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--coa-core", required=True)
    args = ap.parse_args()

    spells = set(json.load(open(os.path.join(MODULE, "client-patch", "coa_manifest.json")))["spells"])
    scripts = ported_scripts()

    setup = "DROP DATABASE IF EXISTS %s; CREATE DATABASE %s;\n" % (SCRATCH, SCRATCH)
    setup += "".join("CREATE TABLE %s.%s LIKE acore_world.%s;\n" % (SCRATCH, t, t) for t in TABLES)
    r = mysql(setup)
    if r.returncode:
        sys.exit(r.stderr.decode())

    replay = []
    root = os.path.join(args.coa_core, "data", "sql", "updates")
    for folder in ("db_world", "pending_db_world"):
        for name in sorted(os.listdir(os.path.join(root, folder))):
            if name.endswith(".sql"):
                replay += statements(os.path.join(root, folder, name))
    r = mysql("\n".join(replay), SCRATCH)
    errors = [line for line in r.stderr.decode().split("\n") if line.startswith("ERROR")]
    print("replayed %d statements, %d failed on Esteria's schema" % (len(replay), len(errors)))
    for line in errors[:8]:
        print("  " + line[:180])

    ids = ",".join(str(s) for s in sorted(spells))
    out = ["-- mod-classless-wildcard: CoA world rows for the imported spells, generated by",
           "-- tools/coa_sql_slice.py from the CoA core's world updates. Do not hand-edit.", ""]
    # the id and script lists go in as tables: thousands of ids do not fit a
    # Windows command line
    mysql("CREATE TABLE wanted_spell (id INT UNSIGNED PRIMARY KEY);\n"
          "INSERT INTO wanted_spell VALUES %s;\n"
          "CREATE TABLE wanted_script (name VARCHAR(64) PRIMARY KEY);\n"
          "INSERT INTO wanted_script VALUES %s;\n"
          % (",".join("(%d)" % s for s in sorted(spells)), ",".join("('%s')" % s for s in sorted(scripts)) or "('-')"),
          SCRATCH)
    for table, col in TABLES.items():
        # no backticks: the filter goes through sh -c, which would run them
        where = "ABS(%s) IN (SELECT id FROM wanted_spell)" % col
        written = "ABS(`%s`) IN (%s)" % (col, ids)
        if table == "spell_script_names":
            # binary: the two tables' collations differ
            where += " AND BINARY ScriptName IN (SELECT BINARY name FROM wanted_script)"
            written += " AND `ScriptName` IN (%s)" % ",".join("'%s'" % s for s in sorted(scripts) or ["-"])
        dump = subprocess.run(
            ["docker", "exec", "ac-database", "sh", "-c",
             'mysqldump -uroot -p"$MYSQL_ROOT_PASSWORD" --no-create-info --skip-triggers --compact '
             '--skip-lock-tables --skip-extended-insert --where="%s" %s %s' % (where, SCRATCH, table)],
            capture_output=True)
        rows = [line for line in dump.stdout.decode("utf-8").split("\n") if line.startswith("INSERT")]
        print("%-22s %d row(s)" % (table, len(rows)))
        if not rows:
            continue
        out.append("DELETE FROM `%s` WHERE %s;" % (table, written))
        out += rows
        out.append("")
    if scripts:
        bound = subprocess.run(["docker", "exec", "ac-database", "sh", "-c",
                                'mysql -uroot -p"$MYSQL_ROOT_PASSWORD" -N -e "SELECT DISTINCT ScriptName FROM '
                                '%s.spell_script_names"' % SCRATCH], capture_output=True).stdout.decode().split()
        print("ported scripts with no binding in CoA's data: %s" % (sorted(scripts - set(bound)) or "none"))
    mysql("DROP DATABASE IF EXISTS %s;" % SCRATCH)

    with open(os.path.join(MODULE, "data", "sql", "db-world", "cw_coa_scripts.sql"), "w",
              encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
