"""Keep CoA server charge metadata and client pools in agreement."""
import re
from pathlib import Path

from coa_spell_affect import dbc_rows


def charge_rows(links, categories, imported, progression):
    categories = {category: (maximum, recovery) for category, maximum, recovery in dbc_rows(categories, 3)}
    roots = {int(spell): int(first) for _cls, first, spell, _level in
             re.findall(r"\{\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\s*\}", progression)}
    rows = {}
    pools = {}
    for spell, category in dbc_rows(links, 2):
        if spell not in imported:
            continue
        maximum, recovery = categories[category]
        if not 1 <= maximum <= 20 or not 1 <= recovery <= 86400000:
            raise ValueError("invalid charge category for spell %d" % spell)
        root = roots.get(spell, spell)
        if root == 707141 and category == 110 and maximum == 3 and recovery == 5000:
            recovery = 6000
        if root in pools and pools[root] != (maximum, recovery):
            raise ValueError("inconsistent charge ranks for spell %d" % root)
        pools[root] = (maximum, recovery)
        row = (spell, maximum, recovery, root, category)
        if spell in rows and rows[spell] != row:
            raise ValueError("duplicate charge metadata for spell %d" % spell)
        rows[spell] = row
    # Tinker's load-time contracts: Overclock and the shared beacon pool.
    if 504594 in imported:
        rows[504594] = (504594, 2, 8000, 504527, 323)
    for spell in (560750, 560754, 801799, 801801, 803799, 803800, 803801, 803802, 803803):
        if spell in rows:
            sid, maximum, recovery, _root, category = rows[spell]
            rows[spell] = (sid, maximum, recovery, 801799, category)
    pools = {}
    for spell, maximum, recovery, root, _category in rows.values():
        if root in pools and pools[root] != (maximum, recovery):
            raise ValueError("inconsistent shared charge pool %d" % root)
        pools[root] = (maximum, recovery)
    return sorted(rows.values())


def write_header(path, rows):
    text = """// Generated by gen_coa_import.py; do not edit.
#ifndef CW_COA_SPELL_CHARGES_DATA_H
#define CW_COA_SPELL_CHARGES_DATA_H

#include <array>
#include <cstdint>

namespace CoASpellCharges
{
struct Entry
{
    uint32_t spell;
    uint32_t maximum;
    uint32_t recovery;
    uint32_t root;
    uint32_t category;
};

inline constexpr std::array<Entry, %d> Entries = {{
""" % len(rows)
    text += "".join("    {%d, %d, %d, %d, %d},\n" % row for row in rows)
    text += "}};\n}\n\n#endif\n"
    Path(path).write_text(text, encoding="utf-8", newline="\n")
