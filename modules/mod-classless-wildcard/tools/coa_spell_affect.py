#!/usr/bin/env python3
"""Export SpellAffect.dbc targets for imported CoA modifier spells."""
import argparse
import json
from pathlib import Path
import struct
import sys


def dbc_rows(data, fields):
    if len(data) < 20:
        raise ValueError("truncated DBC header")
    magic, count, columns, size, strings = struct.unpack_from("<4s4I", data)
    if magic != b"WDBC" or columns != fields or size != fields * 4:
        raise ValueError("unexpected DBC layout")
    if len(data) != 20 + count * size + strings:
        raise ValueError("truncated DBC rows or string block")
    return list(struct.iter_unpack("<%dI" % fields, data[20:20 + count * size]))


def imported_targets(affect_data, spell_data, imported):
    families = {row[0]: row[208] for row in dbc_rows(spell_data, 234)}
    rows = set()
    for _entry, modifier, target in dbc_rows(affect_data, 3):
        if modifier not in imported or not 18 <= families.get(modifier, 0) <= 38:
            continue
        target = target if target < 0x80000000 else target - 0x100000000
        if not target or target == -0x80000000:
            raise ValueError("invalid SpellAffect target")
        rows.add((modifier, target))
    return sorted(rows)


def write_header(path, rows):
    lines = [
        "// Generated by tools/coa_spell_affect.py; do not edit.",
        "#ifndef CW_COA_SPELL_AFFECT_DATA_H",
        "#define CW_COA_SPELL_AFFECT_DATA_H",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace CoASpellAffect",
        "{",
        "struct Entry",
        "{",
        "    uint32_t modifier;",
        "    int32_t target;",
        "};",
        "",
        "inline constexpr std::array<Entry, %d> Targets = {{" % len(rows),
    ]
    lines += ["    {%d, %d}," % row for row in rows]
    lines += ["}};", "}", "", "#endif", ""]
    Path(path).write_text("\n".join(lines), encoding="utf-8", newline="\n")


def client_targets(rows, chains):
    """The native client matches exact IDs; expand signed rank-root references."""
    result = set()
    for modifier, target in rows:
        targets = [spell for spell, _level in chains.get(-target, [])] if target < 0 else [target]
        for spell in targets or [-target]:
            result.add((modifier, spell))
    return sorted(result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--coa-client", required=True)
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    module = Path(__file__).resolve().parent.parent
    sys.path.insert(0, str(module / "client-patch"))
    from lib import coa

    archives = coa.target_archives(args.coa_client)
    _source, affect = coa.winning_file(archives, "DBFilesClient\\SpellAffect.dbc")
    _source, spells = coa.winning_file(archives, "DBFilesClient\\Spell.dbc")
    if affect is None or spells is None:
        raise SystemExit("CoA SpellAffect.dbc or Spell.dbc is missing")
    imported = set(json.loads(Path(args.manifest).read_text(encoding="utf-8"))["spells"])
    rows = imported_targets(affect, spells, imported)
    write_header(args.output, rows)
    print("%d SpellAffect targets for %d imported modifiers" % (len(rows), len({m for m, _ in rows})))


if __name__ == "__main__":
    main()
