#!/usr/bin/env python3
"""Build the client archive for the imported CoA kits (lib/coa.py says why it
is an archive of its own).

  python build_coa_patch.py --coa-client G:/CoAClient/Client --target-client "G:/3.3.5a - Dev"

Writes <target>/Data/Patch-ZZZZZZZZZZZZZZZZZZZZZZZZCoA.MPQ from coa_manifest.json
(written by data/sql/generators/gen_coa_import.py). Close WoW first; the
client reads archives only at startup. --out writes somewhere else instead.
"""
import argparse
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lib import coa, elemental, forged  # noqa: E402
from lib.mpq import write_archive  # noqa: E402


# SpellShapeshiftForm.dbc, 3.3.5a: 35 fields; 2-17 the locale names, 23-26 the creature displays per race group
FORM_FIELDS = 35
FORM_STRINGS = tuple(range(2, 18))
FORM_DISPLAYS = (23, 24, 25, 26)


def dbc_path(table):
    return "DBFilesClient" + coa.SEP + table + ".dbc"


def write_creature_displays(path, display_rows, model_rows, moved, creature_ids):
    """The server's side of the creature displays: the same rows in its `_dbc` tables, and the
    summoned creatures pointed at the displays that moved. Apply after cw_coa_creatures.sql."""
    lines = ["-- mod-classless-wildcard: the CoA creature displays the client patch adds, generated by",
             "-- client-patch/build_coa_patch.py. Do not hand-edit. Apply after cw_coa_creatures.sql.", ""]
    for name, rows, strings, floats in (
            ("CreatureModelData", model_rows, coa.CREATURE_MODEL[2], coa.CREATURE_MODEL_FLOATS),
            ("CreatureDisplayInfo", display_rows, coa.CREATURE_DISPLAY[2], coa.CREATURE_DISPLAY_FLOATS)):
        if rows:
            lines.append("DELETE FROM `%s_dbc` WHERE `ID` IN (%s);" % (name.lower(), ", ".join(str(r[0]) for r in rows)))
            lines += [coa.dbc_row_sql(name, row, table, strings, floats) for _id, row, table in rows]
            lines.append("")
    if moved and creature_ids:
        lines.append("UPDATE `creature_template_model` SET `CreatureDisplayID` = CASE `CreatureDisplayID` %s END"
                     % " ".join("WHEN %d THEN %d" % kv for kv in sorted(moved.items())))
        lines.append("WHERE `CreatureID` IN (%s) AND `CreatureDisplayID` IN (%s);"
                     % (", ".join(str(c) for c in creature_ids), ", ".join(str(o) for o in sorted(moved))))
        lines.append("")
    if display_rows:
        # a display with no creature_model_info row cannot spawn ("has no model ... can't load"); the rows for the
        # CoA ids come from cw_coa_creatures.sql, these cover the ids added here. A row Esteria has wins.
        lines.append("INSERT IGNORE INTO `creature_model_info` (`DisplayID`, `BoundingRadius`, `CombatReach`, "
                     "`Gender`, `DisplayID_Other_Gender`) VALUES")
        lines.append(",\n".join("(%d, 0.5, 1.5, 2, 0)" % row[0] for row in display_rows) + ";")
        lines.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--coa-client", required=True)
    ap.add_argument("--target-client", required=True)
    ap.add_argument("--out")
    args = ap.parse_args()

    here = os.path.dirname(os.path.abspath(__file__))
    manifest = json.load(open(os.path.join(here, "coa_manifest.json"), encoding="utf-8"))
    target = coa.target_archives(args.target_client)
    source = coa.target_archives(args.coa_client)

    def table(arcs, name, fields):
        where, data = coa.winning_file(arcs, dbc_path(name))
        if data is None:
            raise coa.CoAError("no archive carries %s.dbc" % name)
        return coa.Table(data, fields, name), where

    files = {}
    _w, coa_spell = coa.winning_file(source, coa.SPELL)
    coa_spell = coa.apply_clones(coa_spell)   # new ids for the colliding and doubly offered spells
    spell_src = coa.Table(coa_spell, coa.SPELL_FIELDS, "CoA Spell.dbc")
    # plus visuals ported code sends by id (SMSG_ESTERIA_SPELL_VISUAL_OVERRIDE): AscensionCultist.h PresenceTentacleVisual
    code_visuals = {889830}
    visual_ids = sorted(({spell_src.cell(sid, col) for sid in manifest["spells"] for col in coa.SPELL_VISUAL}
                         | code_visuals) - {0, 0xFFFFFFFF})

    fields = {n: coa.VISUAL_TABLES[n][0] for n in coa.VISUAL_TABLES}
    fields["AnimationData"] = 8
    src_tables = {n: table(source, n, fields[n])[0] for n in fields}
    dst_tables = {n: table(target, n, fields[n])[0] for n in fields}
    added, models, sounds, visual_map = coa.visual_closure(src_tables, dst_tables, visual_ids)
    moved = sum(1 for v, to in visual_map.items() if v != to)
    for v in code_visuals:   # the server names these ids; a move would draw the wrong visual
        if visual_map.get(v, v) != v:
            raise coa.CoAError("visual %d sent by ported code would move to %d" % (v, visual_map[v]))
    print("visuals        %d, %d under a new id: %s" % (len(visual_ids), moved,
          ", ".join("%s +%d" % (k, v) for k, v in added.items() if v)))
    for n in coa.VISUAL_TABLES:
        files[dbc_path(n)] = dst_tables[n].data()

    _w, coa_icons = coa.winning_file(source, coa.SPELLICON)
    where, icons = coa.winning_file(target, coa.SPELLICON)
    files[coa.SPELLICON], new, icon_map = coa.append_icons(
        icons, manifest["icon_paths"], max(coa.Table(coa_icons, 2, "CoA SpellIcon.dbc").ids))
    print("SpellIcon.dbc  +%d rows on %s, %d under a new id" % (len(new), os.path.basename(where), len(icon_map)))

    where, spell = coa.winning_file(target, coa.SPELL)
    # The native client now applies family modifiers itself. Retire only the
    # old floor's cost fields, using the mounted server DBC plus its DB overlay.
    costs_path = os.path.join(here, "coa_costs.json")
    if os.path.exists(costs_path):
        costs = json.load(open(costs_path, encoding="utf-8"))
        baseline = coa.Table(spell, coa.SPELL_FIELDS, "client cost baseline")
        spell = bytearray(spell)
        for raw_id, values in costs.items():
            sid = int(raw_id)
            if sid in manifest["spells"] or sid not in baseline.ids:
                continue
            index = baseline.ids[sid]
            for column, value in zip((42, 204), values):
                struct.pack_into("<I", spell, 20 + index * coa.SPELL_FIELDS * 4 + column * 4, value)
        spell = bytes(spell)
        print("spell costs    %d baseline rows restored" % len(costs))
    # plus the spells a description only names for a number (no server row: never cast)
    shipped = manifest["spells"] + manifest.get("text_spells", [])
    files[coa.SPELL], n_spells = coa.append_spells(spell, coa_spell, shipped,
                                                   set(manifest["clear_equip_slot"]), visual_map, icon_map)
    # Guardian's 802629 contract changes the resource to energy on the server.
    if manifest.get("client_power_overrides"):
        patched = coa.Table(files[coa.SPELL], coa.SPELL_FIELDS, "CoA resource contracts")
        for key, power in manifest["client_power_overrides"].items():
            sid = int(key)
            if sid not in manifest["spells"]:
                raise ValueError("resource contract touches an unowned spell")
            struct.pack_into("<I", patched.records, patched.ids[sid] * patched.rec + 41 * 4, power)
        files[coa.SPELL] = patched.data()
    print("Spell.dbc      +%d rows on %s" % (n_spells, os.path.basename(where)))

    # Spellbook tabs (gen_coa_import.py spellbook_tabs): a class line per CoA class, with the class icon as it
    # landed in the patched Spell.dbc, its race/class row, and a SkillLineAbility row per spell it files
    book = manifest.get("spellbook")
    if book and book["lines"]:
        patched = coa.Table(files[coa.SPELL], coa.SPELL_FIELDS, "spellbook icons")
        skill_lines = coa.winning_file(target, dbc_path("SkillLine"))[1]
        race_class = coa.winning_file(target, dbc_path("SkillRaceClassInfo"))[1]
        for line in book["lines"]:
            icon = patched.cell(line["icon_spell"], coa.SPELL_ICONS[0])
            skill_lines, _added = forged.append_skill_line(skill_lines, dict(
                id=line["id"], category=7, name=line["name"], icon=icon))
            race_class, _added = forged.append_skill_race_class(race_class, dict(
                id=line["rci"], skill=line["id"], race_mask=0, class_mask=0, flags=1040, min_level=0, tier=0,
                cost_index=0))
        files[dbc_path("SkillLine")] = skill_lines
        files[dbc_path("SkillRaceClassInfo")] = race_class
        files[dbc_path("SkillLineAbility")], added = elemental.append_skill_lines(
            coa.winning_file(target, dbc_path("SkillLineAbility"))[1], [dict(sla=row) for row in book["sla"]])
        print("spellbook      %d class tabs, %d spells filed" % (len(book["lines"]), added))

    # Wire pool keys match the server's per-rank-root recharge storage.
    charges = manifest.get("charges", [])
    charge_links = sorted((spell, key) for spell, _max, _ms, key, _cat in charges)
    pools = {}
    for _spell, maximum, recovery, key, _category in charges:
        if key in pools and pools[key] != (maximum, recovery):
            raise ValueError("conflicting client charge pool %d" % key)
        pools[key] = (maximum, recovery)
    for name, fields, rows in (("SpellCharges", 2, charge_links),
                               ("SpellChargesCategory", 3,
                                sorted((key, *value) for key, value in pools.items()))):
        files[dbc_path(name)] = struct.pack("<4s4I", b"WDBC", len(rows), fields, fields * 4, 1) + b"".join(
            struct.pack("<%dI" % fields, *row) for row in rows) + b"\0"
    print("spell charges  %d spells, %d recharge pools" % (len(charge_links), len(pools)))
    affect = manifest.get("spell_affect", [])
    files[dbc_path("EsteriaSpellAffect")] = struct.pack("<4s4I", b"WDBC", len(affect), 3, 12, 1) + b"".join(
        struct.pack("<3I", row + 1, modifier, target) for row, (modifier, target) in enumerate(affect)) + b"\0"

    missing = []

    def bring(member, why):
        """Copy a file the target lacks. Returns its bytes either way, or None
        when CoA does not have it either: some CoA effects name models that
        were never shipped, and the CoA client draws nothing for those too."""
        have = coa.winning_file(target, member)[1]
        if have is not None:
            return have
        _w, data = coa.winning_file(source, member)
        if data is None:
            missing.append("%s (%s)" % (member, why))
            return None
        files[member] = data
        return data

    for path in new.values():
        bring(path + ".blp", "icon")
    for effect in sorted(set(models)):
        model = coa.model_path(effect)
        data = bring(model, "effect model")
        if data is not None:
            for dep in coa.model_files(model, data):
                bring(dep, model)
    for sound in sorted(set(sounds)):
        bring(sound, "sound")

    # the weapon enchants the spells apply (effect 112, MiscValue = a SpellItemEnchantment id): CoA's Tinker
    # augmentations name rows 9995-10000, which neither the Esteria client nor its server tables have
    enchantment_ids = {spell_src.cell(sid, 110 + i) for sid in manifest["spells"] for i in range(3)
                       if spell_src.cell(sid, 71 + i) == 112} - {0}
    if enchantment_ids:
        src_enchants, _w = table(source, coa.ENCHANTMENT[0], coa.ENCHANTMENT[1])
        dst_enchants, _w = table(target, coa.ENCHANTMENT[0], coa.ENCHANTMENT[1])
        enchant_rows = coa.append_enchantments(src_enchants, dst_enchants, enchantment_ids)
        files[dbc_path(coa.ENCHANTMENT[0])] = dst_enchants.data()
        print("enchantments   %d used, %d added" % (len(enchantment_ids), len(enchant_rows)))
        lines = ["-- mod-classless-wildcard: the CoA weapon enchants the client patch adds, generated by",
                 "-- client-patch/build_coa_patch.py. Do not hand-edit.", ""]
        if enchant_rows:
            lines.append("DELETE FROM `spellitemenchantment_dbc` WHERE `ID` IN (%s);"
                         % ", ".join(str(r[0]) for r in enchant_rows))
            lines += [coa.dbc_row_sql(coa.ENCHANTMENT[0], row, dst, coa.ENCHANTMENT[2], ())
                      for _id, row, dst in enchant_rows]
        with open(os.path.join(here, "..", "data", "sql", "db-world", "cw_coa_enchantments.sql"), "w",
                  encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")

    # the displays of the summoned creatures (coa_creatures_manifest.json, from tools/coa_creature_slice.py)
    creatures_path = os.path.join(here, "coa_creatures_manifest.json")
    if os.path.exists(creatures_path):
        creatures = json.load(open(creatures_path, encoding="utf-8"))
        src_display, _w = table(source, coa.CREATURE_DISPLAY[0], coa.CREATURE_DISPLAY[1])
        dst_display, _w = table(target, coa.CREATURE_DISPLAY[0], coa.CREATURE_DISPLAY[1])
        src_model, _w = table(source, coa.CREATURE_MODEL[0], coa.CREATURE_MODEL[1])
        dst_model, _w = table(target, coa.CREATURE_MODEL[0], coa.CREATURE_MODEL[1])
        # CoA's own shapeshift forms (Tinker Mechsuit 49, Venomancer Spider 52 and Beetle 53, ...): every row past
        # the target's last form, and the displays they turn the player into
        src_forms, _w = table(source, "SpellShapeshiftForm", FORM_FIELDS)
        dst_forms, _w = table(target, "SpellShapeshiftForm", FORM_FIELDS)
        form_ids = sorted(i for i in src_forms.ids if i > max(dst_forms.ids))
        form_displays = {src_forms.cell(i, col) for i in form_ids for col in FORM_DISPLAYS} - {0}
        display_map, display_rows, model_rows, creature_files = coa.creature_closure(
            src_display, dst_display, src_model, dst_model,
            sorted(set(creatures["creature_displays_used"]) | form_displays))
        files[dbc_path(coa.CREATURE_DISPLAY[0])] = dst_display.data()
        files[dbc_path(coa.CREATURE_MODEL[0])] = dst_model.data()
        for model, textures in creature_files:
            data = bring(model, "creature model")
            if data is not None:
                for dep in coa.model_files(model, data):
                    bring(dep, model)
            for texture in textures:
                bring(texture, "creature texture")
        moved = {old: new for old, new in display_map.items() if old != new}
        print("creatures      %d displays used, %d added (%d under a new id), %d model rows" % (
            len(creatures["creature_displays_used"]), len(display_rows), len(moved), len(model_rows)))
        write_creature_displays(os.path.join(here, "..", "data", "sql", "db-world", "cw_coa_creatures_displays.sql"),
                                display_rows, model_rows, moved, creatures["creatures"])

        # the forms, pointed at the displays as they landed; the server reads the same rows from its overlay table
        form_sql = []
        for form in form_ids:
            row = src_forms.row(form)
            for col in FORM_DISPLAYS:
                display = struct.unpack_from("<I", row, col * 4)[0]
                if display:
                    struct.pack_into("<I", row, col * 4, display_map.get(display, display))
            for col in FORM_STRINGS:
                off = struct.unpack_from("<I", row, col * 4)[0]
                text = src_forms.text(off) if off else ""
                struct.pack_into("<I", row, col * 4, coa._add_string(dst_forms.strings, text) if text else 0)
            dst_forms.append(row)
            form_sql.append(coa.dbc_row_sql("SpellShapeshiftForm", bytes(row), dst_forms, FORM_STRINGS, ()))
        files[dbc_path("SpellShapeshiftForm")] = dst_forms.data()
        if form_sql:
            with open(os.path.join(here, "..", "data", "sql", "db-world", "cw_coa_creatures_displays.sql"),
                      "a", encoding="utf-8", newline="\n") as out_sql:
                out_sql.write("DELETE FROM `spellshapeshiftform_dbc` WHERE `ID` IN (%s);\n"
                              % ", ".join(str(i) for i in form_ids) + "\n".join(form_sql) + "\n\n")
        print("forms          %d CoA shapeshift forms added: %s" % (len(form_ids), form_ids))
        object_ids = creatures.get("gameobject_displays_used", [])
        if object_ids:
            src_objects, _w = table(source, "GameObjectDisplayInfo", 19)
            dst_objects, _w = table(target, "GameObjectDisplayInfo", 19)
            object_map, object_rows, object_models = coa.gameobject_displays(src_objects, dst_objects, object_ids)
            files[dbc_path("GameObjectDisplayInfo")] = dst_objects.data()
            for model in object_models:
                data = bring(model, "summoned gameobject")
                if data is not None:
                    for dep in coa.model_files(model, data):
                        bring(dep, model)
            lines = []
            if object_rows:
                lines.append("DELETE FROM `gameobjectdisplayinfo_dbc` WHERE `ID` IN (%s);" %
                             ",".join(str(row[0]) for row in object_rows))
                lines += [coa.dbc_row_sql("GameObjectDisplayInfo", row, dst, (1,), tuple(range(12, 18)))
                          for _id, row, dst in object_rows]
            moved_objects = {old: new for old, new in object_map.items() if old != new}
            if moved_objects:
                lines.append("UPDATE `gameobject_template` SET `displayId` = CASE `displayId` %s END "
                             "WHERE `entry` IN (%s) AND `displayId` IN (%s);" %
                             (" ".join("WHEN %d THEN %d" % pair for pair in sorted(moved_objects.items())),
                              ",".join(str(i) for i in creatures["gameobjects"]),
                              ",".join(str(i) for i in moved_objects)))
            with open(os.path.join(here, "..", "data", "sql", "db-world", "cw_coa_creatures_displays.sql"),
                      "a", encoding="utf-8", newline="\n") as out_sql:
                out_sql.write("\n".join(lines) + "\n")
            print("gameobjects    %d displays used, %d added" % (len(object_ids), len(object_rows)))
    print("files          %d copied, %d named but in neither client" % (
        len([f for f in files if not f.startswith("DBFilesClient")]), len(missing)))
    for line in missing:
        print("  missing      %s" % line)

    out = args.out or os.path.join(args.target_client, "Data", coa.ARCHIVE)
    size = write_archive(out, files)
    print("wrote %s (%d bytes, %d files)" % (out, size, len(files)))


if __name__ == "__main__":
    main()
