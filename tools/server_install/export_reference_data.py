"""Export only public DBC overrides, never player databases."""
import argparse
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]


def dump_table(container, table, where=None):
    arguments = ["--no-tablespaces", "--set-gtid-purged=OFF", "--single-transaction", "--no-create-info",
                 "--skip-add-locks", "--skip-disable-keys", "--skip-comments", "--skip-set-charset",
                 "--compact", "--complete-insert", "acore_world", table]
    if where:
        arguments.append("--where=" + where)
    return subprocess.run(
        ["docker", "exec", container, "sh", "-c",
         'MYSQL_PWD="$MYSQL_ROOT_PASSWORD" exec mysqldump -uroot "$@"', "export", *arguments],
        capture_output=True, check=True).stdout.decode("utf-8")


def model_info(container):
    where = "DisplayID IN (SELECT ID FROM creaturedisplayinfo_dbc UNION SELECT display FROM esteria_incarnation)"
    ids = query(container, "SELECT DisplayID FROM creature_model_info WHERE " + where).splitlines()
    if not ids or not all(value.isdecimal() for value in ids):
        raise ValueError("Missing or invalid custom display model metadata")
    return ("\nDELETE FROM `creature_model_info` WHERE `DisplayID` IN (" + ",".join(ids) + ");\n"
            + dump_table(container, "creature_model_info", where))


def query(container, sql):
    return subprocess.run(
        ["docker", "exec", "-i", container, "sh", "-c",
         'MYSQL_PWD="$MYSQL_ROOT_PASSWORD" exec mysql -uroot --batch --skip-column-names acore_world'],
        input=sql.encode(), capture_output=True, check=True).stdout.decode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--container", default="ac-database")
    parser.add_argument("--output", type=Path, required=True, help="New SQL file; existing files are never overwritten")
    args = parser.parse_args()
    stores = (ROOT / "src/server/game/DataStores/DBCStores.cpp").read_text(encoding="utf-8")
    tables = sorted(set(re.findall(r'LOAD_DBC\([^;]+?,\s*"([a-z0-9_]+_dbc)"\)', stores)))
    existing = set(query(args.container, "SHOW TABLES;").splitlines())
    tables = [table for table in tables if table in existing]
    with args.output.open("x", encoding="utf-8", newline="\n") as output:
        output.write("-- Esteria public server reference data. No account, character or player state.\n")
        output.write("-- Generated by tools/server_install/export_reference_data.py.\n")
        for table in tables:
            # Table names come only from the checked-in loader and this fixed catalogue allowlist.
            if not int(query(args.container, f"SELECT COUNT(*) FROM `{table}`;")):
                continue
            dump = dump_table(args.container, table)
            ids = query(args.container, f"SELECT `ID` FROM `{table}` ORDER BY `ID`;").splitlines()
            if not all(value.isdecimal() for value in ids):
                raise ValueError(f"Non-numeric reference ID in {table}")
            output.write(f"\nDELETE FROM `{table}` WHERE `ID` IN ({','.join(ids)});\n")
            output.write(dump)
            print(table, len(ids), flush=True)
        output.write(model_info(args.container))


if __name__ == "__main__":
    main()
