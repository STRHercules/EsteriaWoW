"""Publish Housing's ordered SQL through the core updater; --check detects stale copies."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = {
    "world": [
        "housing_world.sql",
        "housing_commerce_world.sql",
        "housing_adventure_world.sql",
        "housing_collections_world.sql",
        "housing_household_world.sql",
    ],
    "characters": ["housing_characters.sql"],
}


def render(database):
    parts = ["-- Generated by tools/server_install/sync_housing_sql.py.\n"]
    for name in SOURCES[database]:
        source = ROOT / "modules/mod-esteria-housing/sql" / database / name
        parts.append(f"-- Source: {source.relative_to(ROOT).as_posix()}\n"
                     f"{source.read_text(encoding='utf-8').rstrip()}\n")
    return "\n".join(parts)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for database in SOURCES:
        target = ROOT / f"data/sql/updates/pending_db_{database}/rev_20261117020000000_housing.sql"
        expected = render(database)
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"Stale Housing migration: {target}")
        else:
            target.write_text(expected, encoding="utf-8", newline="\n")
